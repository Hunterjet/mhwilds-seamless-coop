local t = require("lib.t")
local loopback = require("seamless_coop.net.loopback")

t.test("loopback: delivers after the link latency", function()
    local c = t.clock(0)
    local hub = loopback.new_hub({ clock = c.fn, latency_ms = 100 })
    local a, b = hub:endpoint("loop:a"), hub:endpoint("loop:b")
    t.ok(a:send("loop:b", "hi", true))
    t.eq(#b:poll(10), 0)
    c.advance(0.099)
    t.eq(#b:poll(10), 0)
    c.advance(0.002)
    local got = b:poll(10)
    t.eq(#got, 1)
    t.eq(got[1].from, "loop:a")
    t.eq(got[1].data, "hi")
    t.eq(#a:poll(10), 0)
end)

t.test("loopback: reliable messages stay in order despite jitter", function()
    local c = t.clock(0)
    local hub = loopback.new_hub({ clock = c.fn, latency_ms = 50, jitter_ms = 200, seed = 7 })
    local a, b = hub:endpoint("loop:a"), hub:endpoint("loop:b")
    for i = 1, 20 do a:send("loop:b", tostring(i), true) end
    c.advance(5)
    local got = b:poll(100)
    t.eq(#got, 20)
    for i = 1, 20 do t.eq(got[i].data, tostring(i)) end
end)

t.test("loopback: unreliable messages can drop; reliable never do", function()
    local c = t.clock(0)
    local hub = loopback.new_hub({ clock = c.fn, drop = 1.0 })
    local a, b = hub:endpoint("loop:a"), hub:endpoint("loop:b")
    t.ok(a:send("loop:b", "u", false))
    t.ok(a:send("loop:b", "r", true))
    local got = b:poll(10)
    t.eq(#got, 1)
    t.eq(got[1].data, "r")
    t.eq(hub.dropped, 1)
end)

t.test("loopback: unknown destinations fail; poll respects max", function()
    local c = t.clock(0)
    local hub = loopback.new_hub({ clock = c.fn })
    local a, b = hub:endpoint("loop:a"), hub:endpoint("loop:b")
    t.no(a:send("loop:nobody", "x", true))
    for i = 1, 5 do a:send("loop:b", tostring(i), true) end
    t.eq(#b:poll(2), 2)
    t.eq(#b:poll(10), 3)
    hub:remove_endpoint("loop:b")
    t.no(a:send("loop:b", "x", true))
end)

t.test("loopback: per-link settings override the default", function()
    local c = t.clock(0)
    local hub = loopback.new_hub({ clock = c.fn, latency_ms = 1000 })
    local a, b = hub:endpoint("loop:a"), hub:endpoint("loop:b")
    hub:set_link("loop:b", "loop:a", { latency_ms = 10, jitter_ms = 0, drop = 0 })
    a:send("loop:b", "fast", true)
    c.advance(0.011)
    t.eq(#b:poll(10), 1)
end)
